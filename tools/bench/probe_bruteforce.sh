#!/usr/bin/env bash
# One-command probe for the exact GPU brute-force graph builder.
#
# Installs BOTH bridge sources (seekdb_cuvs_bridge.c and the custom graph
# builder) from the same branch into a seekdb source tree, rebuilds the bridge,
# then measures the scored path (cold CREATE VECTOR INDEX + first query, 4096
# Top-10/Top-100 queries, exact Recall) on real SIFT250K (128d) and on the
# synthetic 256d suite.
#
# Usage:  tools/bench/probe_bruteforce.sh [degree] [port]
#   degree  graph candidate degree, default 256
#   port    base SQL port, default 3031
#
# The SIFT dataset is reused from an existing sweep work directory; the 256d
# dataset is generated by the sweep itself when missing.
set -u
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
SRC=${SEEKDB_SRC:-/work/seekdb-bundle/seekdb}
BR=${SEEKDB_BRIDGE:-/work/bridge/libseekdb_cuvs_bridge.so}
W=/work/bf-run2/sweep
DEG=${1:-256}
PORT=${2:-3031}
say() { echo "[$(date +%H:%M:%S)] $*"; }

[[ -d "$SRC" ]] || { say "FAILED: no source at $SRC"; exit 1; }
[[ -x "$SRC/build_release/src/observer/seekdb" ]] || { say "FAILED: no prebuilt observer"; exit 1; }

# Reuse an existing real-SIFT dataset directory; the 256d suite regenerates.
SIFT=""
for C in /work/cagra-sweep /work/algo-probe-run/sweep /work/sweep /work/bench /work/datasets; do
  [[ -z "$SIFT" && -f "$C/data-sift250k/meta.json" ]] && SIFT="$C/data-sift250k"
done
[[ -n "$SIFT" ]] || { say "FAILED: no data-sift250k/meta.json found"; exit 1; }
mkdir -p "$W"
[[ -L "$W/data-sift250k" ]] && rm -f "$W/data-sift250k"
[[ -L "$W/data-syn256"  ]] && rm -f "$W/data-syn256"
ln -sfn "$SIFT" "$W/data-sift250k"
say "sift=$SIFT syn=<generated if missing> degree=$DEG port=$PORT"

export HIPVS_ROOT=/opt/hipvs ROCM_ROOT=/opt/rocm
W2=/work/bf-run2
mkdir -p "$W2"
rm -f "$W2"/*-timing.log "$W2/timing.log" 2>/dev/null

BUILDER=$HERE/custom_builder.hip
BRIDGEC=$HERE/seekdb_cuvs_bridge.c
[[ -f "$BUILDER"  ]] || BUILDER=$HERE/../hipvs_bridge/kernel_build/custom_builder.hip
[[ -f "$BRIDGEC"  ]] || BRIDGEC=$HERE/../hipvs_bridge/seekdb_cuvs_bridge.c
[[ -f "$BUILDER" && -f "$BRIDGEC" ]] || { say "FAILED: bridge sources not next to this script"; exit 1; }

say "== install bridge sources, rebuild bridge =="
cp "$BUILDER" "$SRC/tools/hipvs_bridge/kernel_build/custom_builder.hip" || exit 1
cp "$BRIDGEC" "$SRC/tools/hipvs_bridge/seekdb_cuvs_bridge.c" || exit 1
sha256sum "$SRC/tools/hipvs_bridge/kernel_build/custom_builder.hip" \
          "$SRC/tools/hipvs_bridge/seekdb_cuvs_bridge.c" | sed 's/^/  installed /'
( cd "$SRC" && tools/hipvs_bridge/build.sh "$BR" ) >"$W2/bridge.log" 2>&1 \
  || { say "FAILED: bridge build"; tail -n 40 "$W2/bridge.log"; exit 1; }
say "bridge ok"

CFGS="bf${DEG}:0:${DEG}:384:128"
[[ "$DEG" != "128" ]] && CFGS="$CFGS bf128:0:128:128:128"
say "== sweep: brute ($CFGS) on sift128 + syn256 =="
( cd "$SRC" && tools/bench/run_contest_sweep.sh \
    --observer build_release/src/observer/seekdb --bridge "$BR" \
    --work "$W" --memory 32G --port "$PORT" \
    --extra-env "SK_CUVS_TIMING_FILE=$W2/timing.log,SK_CUVS_BUILD_ALGO=brute" \
    --configs "$CFGS" ) >"$W2/sweep.log" 2>&1
say "== sweep done =="
echo "---- build_ms / recall ----"
grep -h "\[bench\].*build_ms=" "$W2/sweep.log" | tail -4
echo "---- graph build phases ----"
grep -h "SEEKDB_BF\|SEEKDB_GPU_BUILD\|SEEKDB_BRIDGE_BUILD\|SEEKDB_BRIDGE_SERIALIZE" "$W2/timing.log" 2>/dev/null | tail -25
echo "---- failures ----"
grep -h "FAILED\|failed\|Error\|error" "$W2/timing.log" 2>/dev/null | tail -8
tail -n 8 "$W2/sweep.log"
echo "---- summaries ----"
for f in "$W"/summary-*.tsv; do [[ -f "$f" ]] && { echo "== $f"; cat "$f"; }; done
say "ALL DONE"
