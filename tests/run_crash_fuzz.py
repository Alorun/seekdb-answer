CRASH_POINTS = [
    "after_wal_write",
    "after_commit_fsync",
    "recovery_after_pass1",
    "recovery_after_truncate",
    "checkpoint_before_rename",
    "checkpoint_after_rename",
]
RECOVERY_POINTS = {"recovery_after_pass1", "recovery_after_truncate"}
CHECKPOINT_POINTS = {"checkpoint_before_rename", "checkpoint_after_rename"}
COMMIT_POINTS = {"after_commit_fsync"}

SYNC_TABLE = "__sync"
SYNC_MARKER = "__mvdb_sync__"
# A schema-free sentinel: the engine rejects this unknown session variable with
# a unique ERROR line, so it works before and after any table exists.
SENTINEL_SQL = f"SET {SYNC_MARKER}='1';"
SCHEMA_COLS = ["id", "grp", "val", "embedding"]
HIDDEN_TABLES = {SYNC_TABLE}
VARCHAR_LEN = 32
VEC_DIM = 4


def fmt_vec(vec: Tuple[int, ...]) -> str:
    return "[" + ",".join(str(int(x)) for x in vec) + "]"


def sql_lit(v: Any) -> str:
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, tuple):
        return "'" + fmt_vec(v) + "'"
    s = str(v)
    return "'" + s.replace("\\", "\\\\").replace("'", "''") + "'"


def quote_ident(name: str) -> str:
    # All identifiers generated by this harness are plain ASCII.
    return name


# ---------------------------------------------------------------------------
# SQL operations (structured, so the Python model never parses SQL)
# ---------------------------------------------------------------------------


def op(kind: str, **kw: Any) -> Dict[str, Any]:
    d = {"kind": kind}
    d.update(kw)
    return d


def op_sql(o: Dict[str, Any]) -> str:
    k = o["kind"]
    if k == "create_table":
        return (
            f"CREATE TABLE {quote_ident(o['table'])} (id BIGINT PRIMARY KEY, "
            f"grp VARCHAR({VARCHAR_LEN}), val BIGINT, embedding VECTOR({VEC_DIM}));"
        )
    if k == "create_index":
        return (
            f"CREATE VECTOR INDEX {quote_ident(o['name'])} ON "
            f"{quote_ident(o['table'])}({o.get('column', 'embedding')});"
        )
    if k == "insert":
        rows = []
        for pk, grp, val, vec in o["rows"]:
            rows.append(f"({pk},{sql_lit(grp)},{val},{sql_lit(fmt_vec(vec))})")
        return f"INSERT INTO {quote_ident(o['table'])} VALUES " + ",".join(rows) + ";"
    if k == "update":
        sets = ",".join(f"{c}={sql_lit(v)}" for c, v in o["sets"])
        return f"UPDATE {quote_ident(o['table'])} SET {sets}" + where_sql(o.get("where", [])) + ";"
    if k == "delete":
        return f"DELETE FROM {quote_ident(o['table'])}" + where_sql(o.get("where", [])) + ";"
    if k == "select":
        cols = ",".join(o.get("columns", ["id"]))
        sql = (
            f"SELECT {cols} FROM {quote_ident(o['table'])}"
            + where_sql(o.get("where", []))
            + " ORDER BY id"
        )
        if o.get("limit") is not None:
            sql += f" LIMIT {o['limit']}"
        return sql + ";"
    if k in ("begin", "commit", "rollback"):
        return k.upper() + ";"
    if k == "set":
        return f"SET {o['key']}='{o['value']}';"
    raise AssertionError(f"unknown op kind {k}")


def where_sql(where: List[Tuple[str, str, Any]]) -> str:
    if not where:
        return ""
    parts = [f"{c} {o} {sql_lit(v)}" for c, o, v in where]
    return " WHERE " + " AND ".join(parts)


def explain_op(o: Dict[str, Any]) -> str:
    return op_sql(o)


# ---------------------------------------------------------------------------
# Python model of the committed/transactional state
