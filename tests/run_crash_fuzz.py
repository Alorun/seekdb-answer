#!/usr/bin/env python3
"""Randomized crash/fuzz suite for the MiniVectorDB binary.

The suite drives the real binary through stdin, models the committed database
state in Python, injects crashes either at the deterministic MVDB_CRASH_POINT
hooks or with SIGKILL at a random moment, restarts the database and checks the
recovery invariants against the model.

It intentionally writes only temporary data directories (and an optional log
under /tmp).  It does not modify the repository or rebuild anything.

Usage:
    python3 tests/run_crash_fuzz.py [./build/minivectordb] \
        [--iterations 50] [--seed 1234] [--modes memory,disk]

Exit status is 0 when no failure was found, 1 otherwise.
"""

