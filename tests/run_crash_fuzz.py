@dataclasses.dataclass
class Iteration:
    index: int
    seed: int
    mode: str
    kind: str  # "point" or "kill"
    crash_point: Optional[str] = None
    kill_delay: Optional[float] = None


@dataclasses.dataclass
class RunResult:
    ok: bool
    failure: Optional[Failure] = None
    sql: List[str] = dataclasses.field(default_factory=list)


def ctx_for(it: Iteration, phase: str = "") -> Dict[str, Any]:
    return {
        "seed": it.seed,
        "mode": it.mode,
        "crash": it.crash_point or f"SIGKILL delay={it.kill_delay:.4f}s",
    }


def run_dirty_recovery(binary: str, data_dir: str, it: Iteration,
                       base_world: World) -> Tuple[World, List[str], Optional[Failure]]:
    """Leave an uncommitted (or committed-but-unacked) WAL tail for recovery tests."""
    rng = random.Random(it.seed * 7919 + 5)
    variant = rng.choice(
        ["none", "uncommitted_insert", "uncommitted_update", "uncommitted_delete",
         "uncommitted_insert", "committed_txn"]
    )
    expected = base_world.clone()
    sqls: List[str] = []

    if variant == "none":
        return expected, sqls, None

    point = "after_commit_fsync" if variant == "committed_txn" else "after_wal_write"
    sess = Session(binary, data_dir, it.mode, crash_point=point)
    try:
        if not sess.ready:
            return expected, sqls, Failure("dirty-state process did not become ready",
                                           phase="dirty", **ctx_for(it))
        txn = World(expected.committed)
        act = sess.exec_stmt("BEGIN;")
        sqls.append("BEGIN;")
        exp = txn.execute(op("begin"))
        if not act.acked or not outcomes_equal(exp, act):
            return expected, sqls, Failure("BEGIN for dirty state failed",
                                           phase="dirty", observed=act.lines, **ctx_for(it))

        pk = rng.choice(visible_pks(txn, "t0") or [1])
        if variant == "uncommitted_insert":
            o = op("insert", table="t0", rows=[rand_row(rng, 400000 + rng.randint(0, 1000), "dirty")])
        elif variant == "uncommitted_update":
            o = op("update", table="t0", sets=[("val", 424242)], where=[("id", "=", pk)])
        elif variant == "uncommitted_delete":
            o = op("delete", table="t0", where=[("id", "=", pk)])
        else:
            # committed_txn: a real transaction whose COMMIT is fsynced but
            # never acknowledged before the crash.
            o = op("insert", table="t0", rows=[rand_row(rng, 500000 + rng.randint(0, 1000), "ct")])
        sqls.append(op_sql(o))

        if variant == "committed_txn":
            # The INSERT runs inside the transaction and is legitimately
            # acknowledged; only the COMMIT (after fdatasync) is the crash
            # point and must not be acknowledged.
            act = sess.exec_stmt(op_sql(o))
            exp2 = txn.execute(o)
            if not act.acked or not outcomes_equal(exp2, act):
                return expected, sqls, Failure(
                    "committed dirty txn DML was not acknowledged as expected",
                    phase="dirty",
                    expected=describe_outcome(exp2, act),
                    observed=act.lines, **ctx_for(it))
            sqls.append("COMMIT;")
            act = sess.exec_stmt("COMMIT;")
            if act.acked:
                return expected, sqls, Failure(
                    "COMMIT for committed dirty txn unexpectedly acknowledged",
                    phase="dirty", observed=act.lines, **ctx_for(it))
            # Model the durable commit explicitly: committed <- txn-local state.
            txn.execute(op("commit"))
            expected = txn
        else:
            # Uncommitted: after_wal_write fires inside the first row write and
            # the statement/transaction must never be acknowledged.
            act = sess.exec_stmt(op_sql(o))
            if act.acked:
                return expected, sqls, Failure(
                    f"dirty-state statement unexpectedly completed ({point} did not fire)",
                    phase="dirty", observed=act.lines, **ctx_for(it))
            expected = base_world.clone()

        rc, _extra, stderr = sess.finish()
        if rc != 137:
            return expected, sqls, Failure(
                f"dirty-state crash did not terminate with 137 (rc={rc})",
                phase="dirty", observed=stderr, **ctx_for(it))
        return expected, sqls, None
    finally:
        sess.kill()


def run_recovery_point(binary: str, data_dir: str, it: Iteration,
                       point: str) -> Optional[Failure]:
    env = dict(os.environ)
    env.pop("MVDB_CRASH_POINT", None)
    env["MVDB_CRASH_POINT"] = point
    args = [binary, "--data-dir", data_dir, "--dml-ack"]
    if it.mode == "disk":
        args += ["--memory-rows", "0"]
    try:
        p = subprocess.run(args, input=b"", stdout=subprocess.PIPE,
                           stderr=subprocess.PIPE, env=env, timeout=20)
    except subprocess.TimeoutExpired:
        return Failure(f"recovery crash point {point} hung", phase="recovery",
                       **ctx_for(it))
    if p.returncode != 137:
        return Failure(
            f"recovery crash point {point} did not fire (rc={p.returncode})",
            phase="recovery", observed=(p.stdout + p.stderr).decode("utf-8", "replace"),
            **ctx_for(it))
    return None


def run_iteration(binary: str, it: Iteration,
                  ops_override: Optional[List[Dict[str, Any]]] = None,
                  minimal_base: bool = False) -> RunResult:
    """Run one full crash iteration: base setup, crash, recovery validation."""
    data_dir = tempfile.mkdtemp(prefix=f"mvdb-fuzz-{it.mode}-")
    rng = random.Random(it.seed)
    try:
        base_world, base_ops = setup_base(binary, data_dir, it.mode, it.seed,
                                          minimal=minimal_base)
        if ops_override is not None:
            ops = ops_override
        else:
            ops = generate_workload(rng, base_world, it.crash_point,
                                    length=22 if it.kind == "point" else 80)
        all_sql = [op_sql(o) for o in base_ops] + [op_sql(o) for o in ops]

        if it.kind == "point" and it.crash_point in RECOVERY_POINTS:
            expected_world, dirty_sqls, dfail = run_dirty_recovery(binary, data_dir, it, base_world)
            all_sql += dirty_sqls
            if dfail is not None:
                dfail.sql = all_sql
                return RunResult(False, dfail, all_sql)
            rf = run_recovery_point(binary, data_dir, it, it.crash_point)
            if rf is not None:
                rf.sql = all_sql
                return RunResult(False, rf, all_sql)
            if random.Random(it.seed ^ 0xBEEF).random() < 0.5:
                second = ("recovery_after_truncate"
                          if it.crash_point == "recovery_after_pass1"
                          else "recovery_after_pass1")
                rf2 = run_recovery_point(binary, data_dir, it, second)
                if rf2 is not None:
                    rf2.sql = all_sql
                    return RunResult(False, rf2, all_sql)
            allowed = [expected_world.committed]
            fail, _obs = validate_state(binary, data_dir, it.mode, allowed, ctx_for(it))
            if fail is not None:
                fail.sql = all_sql
                return RunResult(False, fail, all_sql)
            return RunResult(True, None, all_sql)

        if it.kind == "kill":
            sess = Session(binary, data_dir, it.mode)
            timer = threading.Timer(max(0.001, it.kill_delay or 0.01), sess.kill)
            timer.daemon = True
            world = base_world.clone()
            current = None
            sent = False
            try:
                if not sess.ready:
                    return RunResult(False, Failure("process did not become ready",
                                                    phase="startup", **ctx_for(it)), all_sql)
                timer.start()
                for i, o in enumerate(ops):
                    if sess.poll() is not None:
                        break
                    current = o
                    sent = True
                    try:
                        act = sess.exec_stmt(op_sql(o))
                    except HarnessError as e:
                        return RunResult(False, Failure(f"harness error: {e}",
                                                        phase="workload", **ctx_for(it)), all_sql)
                    if not act.acked:
                        break
                    exp = world.execute(o)
                    if not outcomes_equal(exp, act):
                        return RunResult(False, Failure(
                            "semantic mismatch while executing workload",
                            phase="workload",
                            expected=describe_outcome(exp, act),
                            observed=act.lines,
                            **ctx_for(it)), all_sql)
                    current = None
                    sent = False
            finally:
                timer.cancel()
                if sess.poll() is None:
                    sess.kill()
                else:
                    try:
                        sess.p.wait(timeout=5)
                    except Exception:
                        sess.kill()
                rc = sess.p.returncode if sess.p.returncode is not None else -9
                sess.kill()
            # A SIGKILL produces rc=-9; accept any non-clean termination here.
            if rc == 0:
                return RunResult(False, Failure(
                    "random SIGKILL did not terminate the process before it finished",
                    phase="kill", observed="", **ctx_for(it)), all_sql)
            pending = pending_optional(world, current, sent, None)
            allowed = dedupe_states([world.committed] + ([pending] if pending is not None else []))
            fail, _obs = validate_state(binary, data_dir, it.mode, allowed, ctx_for(it))
            if fail is not None:
                fail.sql = all_sql
                return RunResult(False, fail, all_sql)
            return RunResult(True, None, all_sql)

        # Deterministic point run.
        ckpt = 1 if it.crash_point in CHECKPOINT_POINTS else None
        sess = Session(binary, data_dir, it.mode, crash_point=it.crash_point,
                       checkpoint_bytes=ckpt)
        world = base_world.clone()
        current = None
        sent = False
        try:
            if not sess.ready:
                return RunResult(False, Failure("process did not become ready",
                                                phase="startup", **ctx_for(it)), all_sql)
            for i, o in enumerate(ops):
                if sess.poll() is not None:
                    break
                current = o
                sent = True
                act = sess.exec_stmt(op_sql(o))
                if not act.acked:
                    break
                exp = world.execute(o)
                if not outcomes_equal(exp, act):
                    return RunResult(False, Failure(
                        "semantic mismatch before crash point",
                        phase="workload",
                        expected=describe_outcome(exp, act),
                        observed=act.lines,
                        **ctx_for(it)), all_sql)
                current = None
                sent = False

            if it.crash_point in CHECKPOINT_POINTS:
                if current is not None:
                    return RunResult(False, Failure(
                        "workload statement was still in flight before checkpoint",
                        phase="checkpoint", **ctx_for(it)), all_sql)
                rc, extra, stderr = sess.finish()
                if rc != 137:
                    return RunResult(False, Failure(
                        f"checkpoint crash point did not fire (rc={rc})",
                        phase="checkpoint",
                        observed=extra + [stderr], **ctx_for(it)), all_sql)
                allowed = [world.committed]
            elif it.crash_point in COMMIT_POINTS:
                rc, extra, stderr = sess.finish()
                if rc != 137:
                    return RunResult(False, Failure(
                        f"after_commit_fsync did not fire (rc={rc})",
                        phase="commit-crash",
                        observed=extra + [stderr], **ctx_for(it)), all_sql)
                if current is None:
                    return RunResult(False, Failure(
                        "after_commit_fsync fired but no statement was in flight",
                        phase="commit-crash", **ctx_for(it)), all_sql)
                pending = pending_optional(world, current, sent, it.crash_point)
                if pending is None:
                    return RunResult(False, Failure(
                        "could not model the durable pending commit at after_commit_fsync",
                        phase="commit-crash",
                        observed=op_sql(current) if current else "", **ctx_for(it)), all_sql)
                # The crash point is after fdatasync: the commit must survive.
                allowed = [pending]
            else:
                rc, extra, stderr = sess.finish()
                if rc != 137:
                    return RunResult(False, Failure(
                        f"after_wal_write did not fire (rc={rc})",
                        phase="wal-crash",
                        observed=extra + [stderr], **ctx_for(it)), all_sql)
                if current is None:
                    return RunResult(False, Failure(
                        "after_wal_write fired but no statement was in flight",
                        phase="wal-crash", **ctx_for(it)), all_sql)
                # Strict: the write crashed before its commit marker.
                pending = pending_optional(world, current, sent, "after_wal_write")
                allowed = [world.committed]

            fail, _obs = validate_state(binary, data_dir, it.mode, allowed, ctx_for(it))
            if fail is not None:
                fail.sql = all_sql
                return RunResult(False, fail, all_sql)
            return RunResult(True, None, all_sql)
        finally:
            if sess.poll() is None:
                sess.kill()
            else:
                # Ensure pipes/process are reaped even after a crash.
                sess.kill()
    except HarnessError as e:
        return RunResult(False, Failure(f"harness error: {e}", phase="harness",
                                        **ctx_for(it)))
    except Exception:
        return RunResult(False, Failure(
            "harness exception:\n" + traceback.format_exc(), phase="harness",
            **ctx_for(it)))
    finally:
        shutil.rmtree(data_dir, ignore_errors=True)


# ---------------------------------------------------------------------------
# Minimizer
# ---------------------------------------------------------------------------


def minimize_repro(binary: str, it: Iteration, original: Failure,
                   original_ops: List[Dict[str, Any]]) -> Tuple[List[str], str]:
    """Try to shrink the workload prefix that still reproduces the failure."""
    note = ""
    # Determine the original workload operations (the SQL list also contains
    # the base setup; re-running uses the same base, so only the workload is
    # varied here).
    best_ops: Optional[List[Dict[str, Any]]] = None
    best_fail: Optional[Failure] = None

    attempts = 3 if it.kind == "kill" else 1
    reproduced = False
    for _ in range(attempts):
        r = run_iteration(binary, it)
        if not r.ok:
            reproduced = True
            break
    if not reproduced:
        note = ("failure was not reproducible on replay (timing-dependent); "
                "original seed/delay are reported")
        sql = original.sql
        return sql, note

    for k in range(1, len(original_ops) + 1):
        r = run_iteration(binary, it, ops_override=original_ops[:k], minimal_base=True)
        if (not r.ok and r.failure is not None
                and r.failure.phase == original.phase):
            best_ops = original_ops[:k]
            best_fail = r.failure
            break

    if best_ops is None:
        sql = original.sql
        note = "prefix minimization did not preserve the failure"
        return sql, note

    # Build a standalone SQL script for the minimized repro.
    rng = random.Random(it.seed * 1000003 + 17)
    base_ops = build_base_ops(rng, minimal=True)
    lines = [
        f"-- minimized repro: seed={it.seed} mode={it.mode}",
        f"-- crash: {it.crash_point or ('SIGKILL delay=%.4f' % (it.kill_delay or 0))}",
        "-- base:",
    ]
    lines += [op_sql(o) for o in base_ops]
    lines.append("-- workload:")
    lines += [op_sql(o) for o in best_ops]
    if best_fail is not None:
        lines.append(f"-- failure phase: {best_fail.phase}: {best_fail.message}")
        if best_fail.diff:
            lines.append("-- diff:")
            lines += ["-- " + ln for ln in best_fail.diff.splitlines()]
    return lines, note


