# A row is (pk, grp, val, vec_tuple).
Row = Tuple[int, str, int, Tuple[int, ...]]


class Outcome:
    __slots__ = ("ok", "code", "message", "affected", "columns", "rows")

    def __init__(
        self,
        ok: bool = True,
        code: int = 0,
        message: str = "",
        affected: int = 0,
        columns: Optional[List[str]] = None,
        rows: Optional[List[List[str]]] = None,
    ):
        self.ok = ok
        self.code = code
        self.message = message
        self.affected = affected
        self.columns = columns
        self.rows = rows


class State:
    """Committed or transaction-local database state."""

    __slots__ = ("tables", "rows", "indexes")

    def __init__(self) -> None:
        self.tables: Dict[str, bool] = {}
        self.rows: Dict[str, Dict[int, Row]] = {}
        self.indexes: Dict[str, Tuple[str, str]] = {}

    def clone(self) -> "State":
        s = State()
        s.tables = dict(self.tables)
        s.rows = {t: dict(r) for t, r in self.rows.items()}
        s.indexes = dict(self.indexes)
        return s

    def snapshot(self, include_hidden: bool = False) -> Dict[str, Tuple[Tuple[int, Row], ...]]:
        out = {}
        for t, rows in self.rows.items():
            if not include_hidden and t in HIDDEN_TABLES:
                continue
            out[t] = tuple(sorted(rows.items()))
        return out

    def table_set(self, include_hidden: bool = False) -> set:
        return {t for t in self.tables if include_hidden or t not in HIDDEN_TABLES}


class World:
    """Committed state plus at most one explicit transaction."""

    __slots__ = ("committed", "txn")

    def __init__(self, committed: Optional[State] = None) -> None:
        self.committed = committed.clone() if committed is not None else State()
        self.txn: Optional[State] = None

    def clone(self) -> "World":
        w = World(self.committed)
        w.txn = self.txn.clone() if self.txn is not None else None
        return w

    def target(self) -> State:
        return self.txn if self.txn is not None else self.committed

    # -- helpers -----------------------------------------------------------
    def _table(self, name: str) -> Optional[State]:
        t = self.target()
        return t if name in t.tables else None

    def execute(self, o: Dict[str, Any]) -> Outcome:
        k = o["kind"]

        if k == "begin":
            if self.txn is not None:
                return Outcome(False, 1568, "nested transactions are not supported")
            self.txn = self.committed.clone()
            return Outcome(True, 0, affected=0)

        if k == "commit":
            if self.txn is None:
                return Outcome(True, 0, affected=0)
            self.committed = self.txn
            self.txn = None
            return Outcome(True, 0, affected=0)

        if k == "rollback":
            self.txn = None
            return Outcome(True, 0, affected=0)

        if k == "create_table":
            if self.txn is not None:
                return Outcome(False, 1235, "DDL inside a transaction is not supported")
            name = o["table"]
            if name in self.committed.tables:
                return Outcome(False, 1050, f"table already exists: {name}")
            self.committed.tables[name] = True
            self.committed.rows[name] = {}
            return Outcome(True, 0, affected=0)

        if k == "create_index":
            if self.txn is not None:
                return Outcome(False, 1235, "DDL inside a transaction is not supported")
            st = self.committed
            name = o["name"]
            table = o["table"]
            if name in st.indexes:
                return Outcome(False, 1061, f"index already exists: {name}")
            if table not in st.tables:
                return Outcome(False, 1146, f"table not found: {table}")
            st.indexes[name] = (table, o.get("column", "embedding"))
            return Outcome(True, 0, affected=0)

        if k in ("insert", "update", "delete"):
            st = self.target()
            table = o["table"]
            if table not in st.tables:
                return Outcome(False, 1146, f"table not found: {table}")

            if k == "insert":
                # Validate every row before changing anything (statement atomicity).
                seen = set()
                converted: List[Row] = []
                for pk, grp, val, vec in o["rows"]:
                    if len(grp) > VARCHAR_LEN:
                        return Outcome(False, 1406, "value too long")
                    if len(vec) != VEC_DIM:
                        return Outcome(False, 1366, "vector dimension mismatch")
                    if pk in st.rows[table] or pk in seen:
                        return Outcome(False, 1062, f"duplicate primary key: {pk}")
                    seen.add(pk)
                    converted.append((pk, grp, val, tuple(int(x) for x in vec)))
                for row in converted:
                    st.rows[table][row[0]] = row
                return Outcome(True, 0, affected=len(converted))

            if k == "update":
                sets = o["sets"]
                for c, v in sets:
                    if c == "id":
                        return Outcome(False, 1235, "updating the primary key is not supported")
                    if c == "grp" and len(str(v)) > VARCHAR_LEN:
                        return Outcome(False, 1406, "value too long")
                    if c == "embedding" and len(v) != VEC_DIM:
                        return Outcome(False, 1366, "vector dimension mismatch")
                pks = [pk for pk, row in st.rows[table].items() if row_matches(row, o.get("where", []))]
                for pk in pks:
                    row = st.rows[table][pk]
                    vals = [row[0], row[1], row[2], row[3]]
                    names = SCHEMA_COLS
                    for c, v in sets:
                        idx = names.index(c)
                        if c == "embedding":
                            vals[idx] = tuple(int(x) for x in v)
                        else:
                            vals[idx] = v
                    st.rows[table][pk] = (vals[0], vals[1], vals[2], vals[3])
                return Outcome(True, 0, affected=len(pks))

            # delete
            pks = [pk for pk, row in st.rows[table].items() if row_matches(row, o.get("where", []))]
            for pk in pks:
                del st.rows[table][pk]
            return Outcome(True, 0, affected=len(pks))

        if k == "select":
            st = self.target()
            table = o["table"]
            if table not in st.tables:
                return Outcome(False, 1146, f"table not found: {table}")
            cols = list(o.get("columns", ["id"]))
            for c in cols:
                if c not in SCHEMA_COLS:
                    return Outcome(False, 1054, f"unknown column: {c}")
            rows = [r for _, r in st.rows[table].items() if row_matches(r, o.get("where", []))]
            rows.sort(key=lambda r: r[0])
            if o.get("limit") is not None:
                rows = rows[: int(o["limit"])]
            out_rows = []
            for r in rows:
                row_out = []
                for c in cols:
                    if c == "id":
                        row_out.append(str(r[0]))
                    elif c == "grp":
                        row_out.append(r[1])
                    elif c == "val":
                        row_out.append(str(r[2]))
                    else:
                        row_out.append(fmt_vec(r[3]))
                out_rows.append(row_out)
            return Outcome(True, 0, columns=cols, rows=out_rows)

        if k == "set":
            return Outcome(True, 0, affected=0)

        raise AssertionError(f"model cannot execute op {k}")


def compare_values(a: Any, b: Any, opname: str) -> bool:
    if opname == "=":
        return a == b
    if opname == "!=":
        return a != b
    if opname == "<":
        return a < b
    if opname == "<=":
        return a <= b
    if opname == ">":
        return a > b
    if opname == ">=":
        return a >= b
    raise AssertionError(opname)


def row_matches(row: Row, where: List[Tuple[str, str, Any]]) -> bool:
    for col, opname, value in where:
        if col == "id":
            cur = row[0]
        elif col == "grp":
            cur = row[1]
        elif col == "val":
            cur = row[2]
        else:
            return False
        if not compare_values(cur, value, opname):
            return False
    return True


def clone_with_autocommit(state: State, o: Dict[str, Any]) -> Tuple[State, Outcome]:
    w = World(state)
    out = w.execute(o)
    return w.committed, out


# ---------------------------------------------------------------------------
# Session driver: one process, one SQL statement at a time + a sync sentinel
# ---------------------------------------------------------------------------


class HarnessError(RuntimeError):
    pass


class SessionTimeout(HarnessError):
    pass


class Actual:
    __slots__ = ("acked", "kind", "code", "affected", "columns", "rows", "lines")

    def __init__(self, acked: bool, kind: str, lines: List[str], code: int = 0,
                 affected: int = 0, columns: Optional[List[str]] = None,
                 rows: Optional[List[List[str]]] = None):
        self.acked = acked
        self.kind = kind
        self.lines = lines
        self.code = code
        self.affected = affected
        self.columns = columns
        self.rows = rows

    def __repr__(self) -> str:
        return f"Actual(acked={self.acked}, kind={self.kind}, code={self.code}, lines={self.lines!r})"


class Session:
    def __init__(self, binary: str, data_dir: str, mode: str,
                 crash_point: Optional[str] = None,
                 checkpoint_bytes: Optional[int] = None,
                 start_timeout: float = 10.0):
        args = [binary, "--data-dir", data_dir, "--dml-ack"]
        if mode == "disk":
            args += ["--memory-rows", "0"]
        if checkpoint_bytes is not None:
            args += ["--checkpoint-bytes", str(checkpoint_bytes)]
        env = dict(os.environ)
        env.pop("MVDB_CRASH_POINT", None)
        if crash_point is not None:
            env["MVDB_CRASH_POINT"] = crash_point
        self.binary = binary
        self.mode = mode
        self.crash_point = crash_point
        self.p = subprocess.Popen(
            args,
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            bufsize=0,
            env=env,
        )
        self.buf = b""
        self.eof = False
        self.ready = False
        self._start(start_timeout)

    # -- low level ---------------------------------------------------------
    def _fill(self, deadline: float) -> bool:
        """Read one chunk, return False on EOF. Raises SessionTimeout."""
        while True:
            left = deadline - time.monotonic()
            if left <= 0:
                raise SessionTimeout("timed out waiting for binary output")
            try:
                r, _, _ = select.select([self.p.stdout], [], [], left)
            except (ValueError, OSError):
                self.eof = True
                return False
            if not r:
                raise SessionTimeout("timed out waiting for binary output")
            try:
                chunk = os.read(self.p.stdout.fileno(), 65536)
            except (ValueError, OSError):
                self.eof = True
                return False
            if not chunk:
                self.eof = True
                return False
            self.buf += chunk
            return True

    def read_line(self, deadline: float) -> Optional[str]:
        while b"\n" not in self.buf:
            if self.eof:
                if self.buf:
                    line, self.buf = self.buf, b""
                    return line.decode("utf-8", "replace").rstrip("\r")
                return None
            if not self._fill(deadline):
                continue
        line, _, self.buf = self.buf.partition(b"\n")
        return line.decode("utf-8", "replace").rstrip("\r")

    def _start(self, timeout: float) -> None:
        deadline = time.monotonic() + timeout
        while True:
            line = self.read_line(deadline)
            if line is None:
                # Startup died (e.g. a recovery crash point) or failed.
                self.ready = False
                return
            if line == "ready":
                self.ready = True
                return
            # Startup diagnostics should not be on stdout, but tolerate blanks.

    def send(self, sql: str) -> bool:
        if self.p.poll() is not None:
            return False
        sql = sql.strip()
        if not sql.endswith(";"):
            sql += ";"
        try:
            self.p.stdin.write((sql + "\n").encode("utf-8"))
            self.p.stdin.flush()
            return True
        except (BrokenPipeError, OSError):
            return False

    # -- statement execution ----------------------------------------------
    def exec_stmt(self, sql: str, timeout: float = 10.0) -> Actual:
        if not self.send(sql):
            return Actual(False, "none", [])
        self.send(SENTINEL_SQL)
        deadline = time.monotonic() + timeout
        lines: List[str] = []
        saw_sentinel = False
        while True:
            line = self.read_line(deadline)
            if line is None:
                break
            if SYNC_MARKER in line:
                saw_sentinel = True
                break
            lines.append(line)
        return classify_actual(lines, saw_sentinel)

    def finish(self, timeout: float = 10.0) -> Tuple[int, List[str], str]:
        try:
            self.p.stdin.close()
        except (BrokenPipeError, OSError):
            pass
        extra: List[str] = []
        deadline = time.monotonic() + timeout
        if self.p.stdout is not None and not self.p.stdout.closed:
            try:
                while True:
                    line = self.read_line(deadline)
                    if line is None:
                        break
                    extra.append(line)
            except (SessionTimeout, ValueError, OSError):
                self.p.kill()
        try:
            rc = self.p.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            self.p.kill()
            rc = self.p.wait(timeout=5)
        stderr = b""
        try:
            stderr = self.p.stderr.read() or b""
        except Exception:
            pass
        return rc, extra, stderr.decode("utf-8", "replace")

    def kill(self) -> None:
        try:
            if self.p.poll() is None:
                self.p.kill()
        except Exception:
            pass
        try:
            self.p.wait(timeout=5)
        except Exception:
            pass
        try:
            if self.p.stdin:
                self.p.stdin.close()
        except Exception:
            pass
        try:
            self.p.stdout.close()
        except Exception:
            pass
        try:
            self.p.stderr.close()
        except Exception:
            pass

    def poll(self) -> Optional[int]:
        return self.p.poll()


ERROR_RE = re.compile(r"^ERROR (\d+):")
OK_RE = re.compile(r"^OK (\d+)$")


def classify_actual(lines: List[str], saw_sentinel: bool) -> Actual:
    if lines:
        m = ERROR_RE.match(lines[0])
        if m:
            return Actual(True, "error", lines, code=int(m.group(1)))
        m = OK_RE.match(lines[0])
        if m:
            return Actual(True, "ok", lines, affected=int(m.group(1)))
        # SELECT: first line is the header.
        cols = lines[0].split("\t") if lines[0] != "" else []
        rows = [ln.split("\t") for ln in lines[1:] if ln != ""]
        return Actual(saw_sentinel, "select", lines, columns=cols, rows=rows)
    return Actual(False, "none", lines)


def actual_to_outcome(a: Actual) -> Outcome:
    if a.kind == "error":
        return Outcome(False, a.code, message="\n".join(a.lines))
    if a.kind == "ok":
        return Outcome(True, 0, affected=a.affected)
    if a.kind == "select":
        return Outcome(True, 0, columns=a.columns or [], rows=a.rows or [])
    return Outcome(False, 0, message="no output")


def outcomes_equal(exp: Outcome, act: Actual) -> bool:
    if exp.ok != (act.kind != "error"):
        return False
    if not exp.ok:
        return exp.code == act.code
    if exp.columns is not None:
        return exp.columns == (act.columns or []) and [list(r) for r in (exp.rows or [])] == [
            list(r) for r in (act.rows or [])
        ]
    return exp.affected == act.affected


def describe_outcome(exp: Outcome, act: Actual) -> str:
    if exp.columns is not None:
        return f"expected SELECT {exp.columns} {exp.rows!r}, got {act.lines!r}"
    if exp.ok:
        return f"expected OK {exp.affected}, got {act.lines!r}"
    return f"expected ERROR {exp.code}, got {act.lines!r}"


