@dataclasses.dataclass
class Failure:
    message: str
    phase: str = ""
    expected: Any = None
    observed: Any = None
    diff: str = ""
    seed: int = 0
    mode: str = ""
    crash: str = ""
    sql: List[str] = dataclasses.field(default_factory=list)


def snapshot_rows(state: State) -> Dict[str, Optional[Dict[int, Row]]]:
    return {t: dict(state.rows.get(t, {})) if t in state.tables else None
            for t in state.tables if t not in HIDDEN_TABLES}


def diff_snapshots(expected: Dict[str, Optional[Dict[int, Row]]],
                   observed: Dict[str, Optional[Dict[int, Row]]]) -> str:
    lines: List[str] = []
    for t in sorted(set(expected) | set(observed)):
        exp = expected.get(t)
        obs = observed.get(t)
        if exp is None and obs is not None:
            lines.append(f"table {t}: unexpectedly present")
            continue
        if exp is not None and obs is None:
            lines.append(f"table {t}: missing (definition lost)")
            continue
        if exp is None:
            continue
        assert obs is not None
        for pk in sorted(set(exp) | set(obs)):
            if pk not in obs:
                lines.append(f"table {t} pk {pk}: LOST committed row/update (exp={exp[pk]!r})")
            elif pk not in exp:
                lines.append(f"table {t} pk {pk}: EXTRA/resurrected row (obs={obs[pk]!r})")
            elif exp[pk] != obs[pk]:
                lines.append(f"table {t} pk {pk}: WRONG value exp={exp[pk]!r} obs={obs[pk]!r}")
    return "\n".join(lines[:80])


def allowed_descriptions(allowed: List[State]) -> str:
    parts = []
    for i, st in enumerate(allowed):
        parts.append(f"allowed[{i}] tables={sorted(st.table_set())} indexes={sorted(st.indexes)}")
    return "\n".join(parts)


