def read_table(sess: Session, table: str) -> Tuple[Optional[Dict[int, Row]], Optional[str]]:
    act = sess.exec_stmt(
        f"SELECT id, grp, val, embedding FROM {quote_ident(table)} ORDER BY id;"
    )
    if not act.acked:
        return None, "statement not acknowledged"
    if act.kind == "error":
        if act.code == 1146:
            return None, None
        return None, f"unexpected error {act.code}: {act.lines!r}"
    if act.kind != "select":
        return None, f"unexpected output: {act.lines!r}"
    if act.columns != SCHEMA_COLS:
        return None, f"schema/header mismatch: {act.columns!r}"
    rows: Dict[int, Row] = {}
    for r in act.rows or []:
        if len(r) != 4:
            return None, f"bad row: {r!r}"
        try:
            pk = int(r[0])
            val = int(r[2])
        except ValueError:
            return None, f"bad row value: {r!r}"
        if pk in rows:
            return None, f"DUPLICATE PK {pk} in SELECT output"
        vec_txt = r[3].strip()
        if not (vec_txt.startswith("[") and vec_txt.endswith("]")):
            return None, f"bad vector formatting: {r[3]!r}"
        try:
            vec = tuple(int(float(x)) for x in vec_txt[1:-1].split(",") if x != "")
        except ValueError:
            return None, f"bad vector formatting: {r[3]!r}"
        rows[pk] = (pk, r[1], val, vec)
    return rows, None


def probe_index(sess: Session, name: str, table: str) -> str:
    act = sess.exec_stmt(
        f"CREATE VECTOR INDEX {quote_ident(name)} ON {quote_ident(table)}(embedding);"
    )
    if not act.acked:
        return "unacked"
    if act.kind == "error":
        if act.code == 1061:
            return "exists"
        if act.code == 1146:
            return "missing_table"
        return f"error{act.code}"
    return "created"


def validate_state(binary: str, data_dir: str, mode: str, allowed: List[State],
                   ctx: Dict[str, Any]) -> Tuple[Optional[Failure], Optional[Dict[str, Any]]]:
    """Restart, compare to every allowed state, probe indexes and append.

    Returns (failure, observed_snapshot).
    """
    sess = None
    try:
        sess = Session(binary, data_dir, mode)
        if not sess.ready:
            return Failure(
                "validation process did not become ready (recovery/startup failure)",
                phase="startup",
                **ctx,
            ), None

        union_tables = set()
        for st in allowed:
            union_tables |= {t for t in st.tables if t not in HIDDEN_TABLES}

        observed: Dict[str, Optional[Dict[int, Row]]] = {}
        for t in sorted(union_tables):
            rows, err = read_table(sess, t)
            if err:
                return Failure(
                    f"reading table {t}: {err}",
                    phase="read",
                    observed=rows,
                    **ctx,
                ), None
            observed[t] = rows

        def matches(st: State) -> bool:
            exp = snapshot_rows(st)
            obs_present = {t: r for t, r in observed.items() if r is not None}
            if set(exp) != set(obs_present):
                return False
            return all(exp[t] == obs_present[t] for t in exp)

        if not any(matches(st) for st in allowed):
            diffs = []
            for i, st in enumerate(allowed):
                diffs.append(f"--- vs allowed[{i}] ---\n" + diff_snapshots(snapshot_rows(st), observed))
            return Failure(
                "recovered state differs from every allowed state",
                phase="recover",
                expected=allowed_descriptions(allowed),
                observed=repr(observed),
                diff="\n".join(diffs),
                **ctx,
            ), observed

        # Index metadata: a second CREATE VECTOR INDEX with the same name must
        # report 1061 iff the index survived the crash.
        union_indexes: Dict[str, str] = {}
        for st in allowed:
            for name, (table, _col) in st.indexes.items():
                union_indexes[name] = table
        index_actual: Dict[str, str] = {}
        for name in sorted(union_indexes):
            table = union_indexes[name]
            index_actual[name] = probe_index(sess, name, table)

        def index_matches(st: State) -> bool:
            for name, actual in index_actual.items():
                expected = "exists" if name in st.indexes else "absent"
                table = union_indexes[name]
                if expected == "exists" and table not in st.tables:
                    return False
                if expected == "absent":
                    want = "missing_table" if table not in st.tables else "created"
                else:
                    want = "exists"
                if actual != want:
                    return False
            return True

        if not any(index_matches(st) for st in allowed):
            return Failure(
                "index metadata probe disagrees with every allowed state",
                phase="index",
                expected=allowed_descriptions(allowed),
                observed=repr(index_actual),
                **ctx,
            ), observed

        # Append after recovery, then restart and verify it is durable.
        if "t0" not in observed or observed["t0"] is None:
            return Failure("t0 is missing before append test", phase="append", **ctx), observed
        before_t0 = dict(observed["t0"])
        append_pk = 900000 + (int(ctx.get("seed", 0)) % 100000)
        while append_pk in before_t0:
            append_pk += 1
        act = sess.exec_stmt(
            f"INSERT INTO t0 VALUES ({append_pk},'appended',777,'[2,2,2,2]');"
        )
        if not act.acked or act.kind != "ok":
            return Failure(
                "INSERT after recovery was not acknowledged",
                phase="append",
                observed=act.lines,
                **ctx,
            ), observed
        rc, extra, stderr = sess.finish()
        sess = None
        if rc != 0:
            return Failure(
                f"clean shutdown after append failed rc={rc}",
                phase="append-shutdown",
                observed=stderr,
                **ctx,
            ), observed

        sess2 = Session(binary, data_dir, mode)
        try:
            if not sess2.ready:
                return Failure("restart after append did not become ready", phase="append-restart", **ctx), observed
            rows2, err2 = read_table(sess2, "t0")
            if err2:
                return Failure(f"append restart read failed: {err2}", phase="append-restart", **ctx), observed
            exp_rows = dict(before_t0)
            exp_rows[append_pk] = (append_pk, "appended", 777, (2, 2, 2, 2))
            if rows2 != exp_rows:
                return Failure(
                    "WAL append/recovery mismatch after restart",
                    phase="append-restart",
                    expected=repr(exp_rows),
                    observed=repr(rows2),
                    diff=diff_snapshots({"t0": exp_rows}, {"t0": rows2}),
                    **ctx,
                ), observed
        finally:
            rc2, _, stderr2 = sess2.finish()
            if rc2 != 0:
                return Failure(
                    f"clean shutdown after append restart failed rc={rc2}",
                    phase="append-restart",
                    observed=stderr2,
                    **ctx,
                ), observed
        return None, observed
    except HarnessError as e:
        return Failure(f"harness/process error: {e}", phase="harness", **ctx), None
    finally:
        if sess is not None:
            sess.kill()


