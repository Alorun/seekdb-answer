def pending_optional(world: World, current: Optional[Dict[str, Any]], sent: bool,
                     crash_point: Optional[str]) -> Optional[State]:
    """Return the state that would result if the in-flight statement committed."""
    if not sent or current is None:
        return None
    kind = current["kind"]

    if crash_point == "after_wal_write":
        # Crash happens inside writeRowRecord, before any commit marker for
        # this statement/transaction.  It must be fully absent.
        return None

    if crash_point == "after_commit_fsync":
        if kind == "commit":
            return world.txn.clone() if world.txn is not None else None
        if kind in ("insert", "update", "delete", "create_table", "create_index"):
            if world.txn is not None:
                return None
            st, _out = clone_with_autocommit(world.committed, current)
            return st
        return None

    # Random SIGKILL: the statement may or may not have committed.
    if kind in ("insert", "update", "delete", "create_table", "create_index"):
        if world.txn is not None:
            return None
        st, _out = clone_with_autocommit(world.committed, current)
        return st
    if kind == "commit":
        return world.txn.clone() if world.txn is not None else None
    return None


def dedupe_states(states: List[State]) -> List[State]:
    out: List[State] = []
    seen = set()
    for st in states:
        sig = (tuple(sorted(st.table_set())), tuple(sorted(st.snapshot().items())),
               tuple(sorted(st.indexes.items())))
        if sig in seen:
            continue
        seen.add(sig)
        out.append(st)
    return out


def run_until_statement_fails(sess: Session, world: World, ops: List[Dict[str, Any]],
                              crash_mode: str, timeout: float = 10.0):
    """Execute ops; return (acked_count, current_op, sent, failure_outcome)."""
    current = None
    sent = False
    for i, o in enumerate(ops):
        if sess.poll() is not None:
            return i, None, False, None
        sql = op_sql(o)
        current = o
        sent = True
        try:
            act = sess.exec_stmt(sql, timeout=timeout)
        except HarnessError:
            raise
        if not act.acked:
            return i, current, sent, None
        exp = world.execute(o)
        if not outcomes_equal(exp, act):
            return i, current, sent, (sql, exp, act)
        current = None
        sent = False
    return len(ops), None, False, None


