def build_base_ops(rng: random.Random, minimal: bool = False) -> List[Dict[str, Any]]:
    ops: List[Dict[str, Any]] = []
    tables = ["t0"] if minimal else ["t0", "t1", "t_empty"]
    for t in tables:
        ops.append(op("create_table", table=t))

    groups = ["g0", "g1", "g2", "g3"]
    pks = [1, 2, 3] if minimal else [1, 2, 3, 4, 5, 6]
    rows = []
    for pk in pks:
        rows.append((pk, groups[pk % len(groups)], pk * 10, (pk % 7 - 3, 1, -1, 2)))
    ops.append(op("insert", table="t0", rows=rows))

    if not minimal:
        rows1 = []
        for pk in [1, 2, 3, 4]:
            rows1.append((pk, groups[(pk + 2) % len(groups)], 100 + pk, (0, pk, 1, -2)))
        ops.append(op("insert", table="t1", rows=rows1))
        ops.append(op("create_index", name="ix0", table="t0"))
        ops.append(op("create_index", name="ix1", table="t1"))

    return ops


def setup_base(binary: str, data_dir: str, mode: str, seed: int,
               minimal: bool = False) -> Tuple[World, List[Dict[str, Any]]]:
    rng = random.Random(seed * 1000003 + 17)
    ops = build_base_ops(rng, minimal=minimal)
    world = World()
    sess = Session(binary, data_dir, mode)
    try:
        if not sess.ready:
            raise HarnessError("binary did not print ready marker during base setup")
        for o in ops:
            sql = op_sql(o)
            act = sess.exec_stmt(sql)
            exp = world.execute(o)
            if not act.acked:
                raise HarnessError(f"base setup statement was not acknowledged: {sql}")
            if not outcomes_equal(exp, act):
                raise HarnessError(
                    f"base setup semantic mismatch for {sql}: {describe_outcome(exp, act)}"
                )
    finally:
        rc, extra, stderr = sess.finish()
    if rc != 0:
        raise HarnessError(f"base setup clean shutdown failed rc={rc} stderr={stderr!r}")
    return world, ops


def visible_pks(world: World, table: str) -> List[int]:
    st = world.target()
    if table not in st.tables:
        return []
    return list(st.rows[table].keys())


def existing_tables(world: World) -> List[str]:
    return sorted(t for t in world.committed.tables if t not in HIDDEN_TABLES)


def visible_tables(world: World) -> List[str]:
    return sorted(t for t in world.target().tables if t not in HIDDEN_TABLES)


def rand_row(rng: random.Random, pk: int, grp: str) -> Row:
    return (pk, grp, rng.randint(-50, 200), tuple(rng.randint(-3, 3) for _ in range(VEC_DIM)))


def generate_workload(rng: random.Random, base_world: World, crash_point: Optional[str],
                      length: int) -> List[Dict[str, Any]]:
    """Generate a random but model-tracked workload.

    The planner follows the same semantics as the Python model, so duplicate
    primary keys and other syntax/constraint errors are intentionally mixed in.
    """
    planner = base_world.clone()
    ops: List[Dict[str, Any]] = []
    counter = {"table": 0, "index": 0, "pk": [1000]}
    saw_commit = False

    def add(o: Dict[str, Any]) -> Outcome:
        nonlocal saw_commit
        if o["kind"] == "commit":
            saw_commit = True
        elif o["kind"] in ("insert", "update", "delete", "create_table", "create_index"):
            if planner.txn is None:
                saw_commit = True
        ops.append(o)
        return planner.execute(o)

    def fresh_pk() -> int:
        counter["pk"][0] += rng.randint(1, 5)
        return counter["pk"][0]

    def pick_table(allow_empty: bool = False) -> str:
        tables = visible_tables(planner)
        if not tables:
            tables = ["t0"]
        if not allow_empty:
            nonempty = [t for t in tables if planner.target().rows.get(t)]
            if nonempty:
                tables = nonempty
        return rng.choice(tables)

    def pick_existing_pk(table: str) -> Optional[int]:
        pks = visible_pks(planner, table)
        return rng.choice(pks) if pks else None

    def make_where(table: str) -> List[Tuple[str, str, Any]]:
        st = planner.target()
        rows = st.rows.get(table, {})
        choices = ["id", "grp", "val"]
        col = rng.choice(choices)
        if col == "id":
            pk = pick_existing_pk(table)
            opname = rng.choice(["=", "=", "=", ">=", "<=", "!="])
            return [("id", opname, pk if pk is not None else 1)]
        if col == "grp":
            existing = sorted({r[1] for r in rows.values()})
            val = rng.choice(existing) if existing and rng.random() < 0.8 else rng.choice(["g0", "gX"])
            opname = rng.choice(["=", "=", "!=", "<", ">="])
            return [("grp", opname, val)]
        existing_vals = sorted({r[2] for r in rows.values()})
        val = rng.choice(existing_vals) if existing_vals and rng.random() < 0.8 else rng.randint(0, 100)
        opname = rng.choice([">", ">=", "<", "<=", "=", "!="])
        where = [("val", opname, val)]
        if rng.random() < 0.3:
            pk = pick_existing_pk(table)
            if pk is not None:
                where.append(("id", "!=", pk))
        return where

    # Guarantee an early row write so after_wal_write always has something to
    # crash on, and guarantee at least one commit for after_commit_fsync.
    first = rng.random()
    if first < 0.30:
        add(op("begin"))
        add(op("insert", table="t0", rows=[rand_row(rng, fresh_pk(), rng.choice(["g0", "g1", "g2"]))]))
        txn_open = True
    else:
        add(op("insert", table="t0", rows=[rand_row(rng, fresh_pk(), rng.choice(["g0", "g1", "g2"]))]))
        txn_open = False

    while len(ops) < length:
        if txn_open:
            r = rng.random()
            if r < 0.20:
                add(op("commit"))
                txn_open = False
                continue
            if r < 0.30:
                add(op("rollback"))
                txn_open = False
                continue
            # DML inside the transaction.
            kind = rng.choices(["insert", "update", "delete", "select"], [4, 3, 2, 2])[0]
        else:
            r = rng.random()
            if r < 0.16:
                add(op("begin"))
                txn_open = True
                continue
            if r < 0.22:
                # DDL (autocommit) or occasional duplicate-DDL error.
                if rng.random() < 0.5 or not existing_tables(planner):
                    counter["table"] += 1
                    name = f"nt{counter['table']}"
                    add(op("create_table", table=name))
                    if rng.random() < 0.45:
                        # First rows of a brand-new table inside a transaction:
                        # in --memory-rows 0 mode this exercises the
                        # memory->disk spill path with rollback/commit.
                        add(op("begin"))
                        add(op("insert", table=name,
                                rows=[rand_row(rng, fresh_pk(), rng.choice(["g0", "g1"]))]))
                        txn_open = True
                else:
                    counter["index"] += 1
                    table = pick_table()
                    add(op("create_index", name=f"ix{counter['index'] + 10}", table=table))
                continue
            kind = rng.choices(
                ["insert", "update", "delete", "select"], [5, 4, 3, 3]
            )[0]

        if kind == "insert":
            table = pick_table()
            nrows = rng.randint(1, 3)
            rows = [rand_row(rng, fresh_pk(), rng.choice(["g0", "g1", "g2", "g3"])) for _ in range(nrows)]
            mode = rng.random()
            if mode < 0.20:
                # Duplicate an existing PK (statement must fail atomically).
                pk = pick_existing_pk(table)
                if pk is not None:
                    rows.insert(rng.randint(0, len(rows)), rand_row(rng, pk, "dup"))
            elif mode < 0.30:
                # Duplicate within the batch itself.
                if len(rows) >= 1:
                    pk = rows[0][0]
                    rows.insert(rng.randint(1, len(rows)), rand_row(rng, pk, "dup2"))
            elif mode < 0.36:
                # Validation failure after possibly writing earlier rows.
                bad = rand_row(rng, fresh_pk(), "x" * (VARCHAR_LEN + 3))
                rows.insert(rng.randint(0, len(rows)), bad)
            elif mode < 0.42:
                bad = rand_row(rng, fresh_pk(), "badvec")
                rows.insert(rng.randint(0, len(rows)), (bad[0], bad[1], bad[2], (1, 2)))
            add(op("insert", table=table, rows=rows))

        elif kind == "update":
            table = pick_table(allow_empty=True)
            sets = []
            if rng.random() < 0.8:
                sets.append(("grp", rng.choice(["g0", "g1", "g2", "g3", "g9"])))
            if rng.random() < 0.8:
                sets.append(("val", rng.randint(-100, 300)))
            if not sets or rng.random() < 0.4:
                sets.append(("embedding", tuple(rng.randint(-3, 3) for _ in range(VEC_DIM))))
            if rng.random() < 0.03:
                sets.append(("id", 999999))
            where = [] if rng.random() < 0.12 else make_where(table)
            add(op("update", table=table, sets=sets, where=where))

        elif kind == "delete":
            table = pick_table(allow_empty=True)
            where = [] if rng.random() < 0.10 else make_where(table)
            add(op("delete", table=table, where=where))

        else:  # select
            table = pick_table(allow_empty=True)
            cols = rng.choice(
                [["id"], ["id", "grp"], ["id", "val"], ["id", "grp", "val"], ["*"]]
            )
            if cols == ["*"]:
                cols = list(SCHEMA_COLS)
            where = [] if rng.random() < 0.55 else make_where(table)
            limit = None
            if rng.random() < 0.35:
                limit = rng.choice([0, 1, 2, 5, 100])
            add(op("select", table=table, columns=cols, where=where, limit=limit))

    if txn_open:
        if crash_point in CHECKPOINT_POINTS and rng.random() < 0.5:
            # Leave the transaction open: EOF makes the engine roll it back
            # before the shutdown checkpoint.  Recovery must not expose it.
            pass
        elif crash_point in CHECKPOINT_POINTS or not saw_commit:
            add(op("commit"))
    elif not saw_commit:
        # Ensure after_commit_fsync has a commit to crash on (the guaranteed
        # early write may have been rolled back).
        add(op("insert", table="t0",
                rows=[rand_row(rng, fresh_pk(), rng.choice(["g0", "g1", "g2"]))]))
    return ops


