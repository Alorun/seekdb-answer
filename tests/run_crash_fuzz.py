def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("binary", nargs="?", default="./build/minivectordb")
    ap.add_argument("--iterations", type=int, default=80,
                    help="iterations per mode (default 80)")
    ap.add_argument("--seed", type=int, default=20261109)
    ap.add_argument("--modes", default="memory,disk")
    ap.add_argument("--max-failures", type=int, default=10)
    ap.add_argument("--keep-going", action="store_true",
                    help="continue after a failure (default: stop after max-failures)")
    args = ap.parse_args()

    binary = os.path.abspath(args.binary)
    if not os.path.exists(binary):
        raise SystemExit(f"binary not found: {binary}")
    modes = [m.strip() for m in args.modes.split(",") if m.strip()]
    for m in modes:
        if m not in ("memory", "disk"):
            raise SystemExit(f"unknown mode: {m}")

    log_path = os.path.join(tempfile.gettempdir(),
                            f"mvdb_crash_fuzz_{int(time.time())}.log")
    log = open(log_path, "w", encoding="utf-8")

    def logline(s: str = "") -> None:
        print(s)
        log.write(s + "\n")
        log.flush()

    logline(f"binary={binary}")
    logline(f"modes={modes} iterations_per_mode={args.iterations} base_seed={args.seed}")
    logline(f"log={log_path}")
    logline("")

    total = 0
    failures: List[Tuple[Iteration, Failure, List[str]]] = []
    point_counts: Dict[str, int] = {}
    kill_count = 0
    t_start = time.monotonic()

    for mode in modes:
        mode_fail = 0
        for i in range(args.iterations):
            seed = args.seed + (0 if mode == "memory" else 100000) + i * 13
            # ~2/3 deterministic crash points (each covered equally), 1/3 SIGKILL.
            if i % 3 != 2:
                cp = CRASH_POINTS[(i // 3 + (0 if mode == "memory" else 3)) % len(CRASH_POINTS)]
                it = Iteration(i, seed, mode, "point", crash_point=cp)
                point_counts[cp] = point_counts.get(cp, 0) + 1
            else:
                rng = random.Random(seed ^ 0x5EED)
                delay = rng.uniform(0.0005, 0.015)
                it = Iteration(i, seed, mode, "kill", kill_delay=delay)
                kill_count += 1
            total += 1
            r = run_iteration(binary, it)
            if not r.ok and r.failure is not None:
                mode_fail += 1
                failures.append((it, r.failure, r.sql))
                logline(
                    f"FAIL [{mode}] iter={i} seed={seed} "
                    f"crash={it.crash_point or ('SIGKILL %.4fs' % (it.kill_delay or 0))}"
                )
                logline(f"  phase={r.failure.phase} message={r.failure.message}")
                if r.failure.diff:
                    logline("  diff:")
                    for ln in r.failure.diff.splitlines():
                        logline("    " + ln)
                if r.failure.expected:
                    logline(f"  expected={r.failure.expected}")
                if r.failure.observed:
                    logline(f"  observed={r.failure.observed}")
                logline("  sql:")
                for ln in r.sql:
                    logline("    " + ln)
                if len(failures) >= args.max_failures and not args.keep_going:
                    logline(f"stopping after {len(failures)} failure(s)")
                    break
            if (i + 1) % 10 == 0 or i + 1 == args.iterations:
                logline(f"[{mode}] {i + 1}/{args.iterations} "
                        f"failures={mode_fail} elapsed={time.monotonic() - t_start:.1f}s")
        if len(failures) >= args.max_failures and not args.keep_going:
            break

    # Minimize failures.
    minimized = []
    if failures:
        logline("")
        logline("=== minimizing failures ===")
        for it, fail, sql in failures[: min(3, len(failures))]:
            try:
                repro, note = minimize_failure_generic(binary, it, fail, logline)
            except Exception:
                repro = sql
                note = "minimizer crashed; original SQL retained"
            minimized.append((it, fail, repro, note))

    elapsed = time.monotonic() - t_start
    logline("")
    logline("=== summary ===")
    logline(f"iterations={total} elapsed={elapsed:.1f}s")
    logline(f"deterministic crash points={point_counts}")
    logline(f"random SIGKILL iterations={kill_count}")
    logline(f"failures={len(failures)}")
    if minimized:
        for it, fail, repro, note in minimized:
            logline("")
            logline(f"minimized repro seed={it.seed} mode={it.mode} crash={it.crash_point or it.kill_delay}")
            if note:
                logline(f"note: {note}")
            for ln in repro:
                logline(ln)
    log.close()
    if failures:
        print(f"log: {log_path}")
        return 1
    print(f"all crash/fuzz checks passed ({total} iterations); log: {log_path}")
    return 0


def minimize_failure_generic(binary: str, it: Iteration, fail: Failure, logline) -> Tuple[List[str], str]:
    """Regenerate the workload for an iteration and minimize by prefix."""
    if it.kind == "point" and it.crash_point in RECOVERY_POINTS:
        # Recovery repros include an uncommitted/committed dirty WAL tail that
        # is built from the seed; prefix-minimizing the SQL would drop it.
        return fail.sql or [], "recovery repro reported in full (dirty tail depends on seed)"
    rng = random.Random(it.seed)
    try:
        base_dir = tempfile.mkdtemp(prefix="mvdb-min-base-")
        try:
            base_world, _ = setup_base(binary, base_dir, it.mode, it.seed)
        finally:
            shutil.rmtree(base_dir, ignore_errors=True)
        ops = generate_workload(rng, base_world, it.crash_point,
                                length=22 if it.kind == "point" else 30)
    except Exception:
        return fail.sql or [], "could not regenerate workload for minimization"
    return minimize_repro(binary, it, fail, ops)


if __name__ == "__main__":
    sys.exit(main())
